import React from 'react';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { it, expect, vi, afterEach } from 'vitest';
import { WorkspacesView, type Workspace } from './WorkspacesView';
import { apiRequest } from '../../services/api';
vi.mock('../../services/api', () => ({apiRequest:vi.fn()}));
afterEach(() => vi.resetAllMocks());
const workspace: Workspace = {id:'w',name:'业务空间 A',version:1,kb_ids:['gone'],source_ids:[],status:'invalid',unavailable_kb_ids:['gone'],unavailable_source_ids:[]};
const props = {workspaces:[workspace],knowledgeBases:[],dataSources:[],editRequest:{id:'w',sequence:1},onSaved:vi.fn(),onStart:vi.fn(),onReturn:vi.fn(),onManage:vi.fn()};
it('requires explicit removal of unavailable associations and preserves the form on failure', async () => {
  const user=userEvent.setup(); render(<WorkspacesView {...props} />);
  expect(screen.getByRole('button',{name:'保存'})).toBeDisabled();
  const invalid=screen.getByRole('checkbox',{name:'已失效或无权限的知识库（移除关联）'});
  expect(invalid).toBeChecked();
  await user.click(invalid);
  await user.clear(screen.getByRole('textbox',{name:'空间名称'}));
  await user.type(screen.getByRole('textbox',{name:'空间名称'}),'更新名称');
  vi.mocked(apiRequest).mockRejectedValueOnce(new Error('服务暂时不可用'));
  await user.click(screen.getByRole('button',{name:'保存'}));
  expect(await screen.findByText('服务暂时不可用')).toBeInTheDocument();
  expect(screen.getByRole('textbox',{name:'空间名称'})).toHaveValue('更新名称');
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument();
  vi.mocked(apiRequest).mockResolvedValueOnce({...workspace,name:'更新名称',kb_ids:[],status:'empty',version:2});
  await user.click(screen.getByRole('button',{name:'保存'}));
  await waitFor(() => expect(props.onSaved).toHaveBeenCalled());
  expect(apiRequest).toHaveBeenLastCalledWith('/workspaces/w',expect.objectContaining({body:JSON.stringify({name:'更新名称',kb_ids:[],source_ids:[],version:1})}));
});
it('cancel leaves configuration untouched', async () => {
  const user=userEvent.setup(); render(<WorkspacesView {...props} />);
  await user.type(screen.getByRole('textbox',{name:'空间名称'}),'临时修改');
  await user.click(screen.getByRole('button',{name:'取消'}));
  expect(apiRequest).not.toHaveBeenCalled();
  expect(screen.getByRole('heading',{name:'业务空间 A'})).toBeInTheDocument();
});
